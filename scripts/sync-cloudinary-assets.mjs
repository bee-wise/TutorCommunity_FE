// Generates .agents/assets-inventory.md (raw list) from the Cloudinary account (Admin API).
// The classified catalog .agents/assets.md is hand-curated; this script only reports assets missing from it.
// Usage (PowerShell, repo root): npm run assets:sync
// Reads CLOUDINARY_* from .env.local. Only public delivery URLs are written; never the key/secret.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const env = Object.fromEntries(
  readFileSync(resolve(root, ".env.local"), "utf8")
    .split(/\r?\n/)
    .filter((l) => /^\s*CLOUDINARY_\w+\s*=/.test(l))
    .map((l) => {
      const i = l.indexOf("=");
      return [l.slice(0, i).trim(), l.slice(i + 1).trim().replace(/^["']|["']$/g, "")];
    }),
);
const { CLOUDINARY_CLOUD_NAME: cloud, CLOUDINARY_API_KEY: key, CLOUDINARY_API_SECRET: secret } = env;
if (!cloud || !key || !secret) throw new Error("Missing CLOUDINARY_* in .env.local");

const auth = "Basic " + Buffer.from(`${key}:${secret}`).toString("base64");

async function list(type) {
  const out = [];
  let cursor;
  do {
    const url = new URL(`https://api.cloudinary.com/v1_1/${cloud}/resources/${type}`);
    url.searchParams.set("max_results", "500");
    url.searchParams.set("tags", "true");
    url.searchParams.set("context", "true");
    if (cursor) url.searchParams.set("next_cursor", cursor);
    const res = await fetch(url, { headers: { Authorization: auth } });
    if (!res.ok) throw new Error(`${type}: HTTP ${res.status} ${await res.text()}`);
    const data = await res.json();
    out.push(...data.resources);
    cursor = data.next_cursor;
  } while (cursor);
  return out;
}

const deliveryUrl = (r) => {
  const tx = r.resource_type === "image" && r.format !== "svg" ? "f_auto,q_auto/" : "";
  const ext = r.format ? `.${r.format}` : "";
  return `https://res.cloudinary.com/${cloud}/${r.resource_type}/upload/${tx}v${r.version}/${r.public_id}${ext}`;
};
const folderOf = (r) =>
  r.asset_folder || (r.public_id.includes("/") ? r.public_id.split("/").slice(0, -1).join("/") : "(root)");
const cell = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\r?\n/g, " ");

const all = [];
for (const type of ["image", "video", "raw"]) all.push(...(await list(type)));

const groups = new Map();
for (const r of all.sort((a, b) => a.public_id.localeCompare(b.public_id))) {
  const f = folderOf(r);
  if (!groups.has(f)) groups.set(f, []);
  groups.get(f).push(r);
}

const catalog = (() => { try { return readFileSync(resolve(root, ".agents/assets.md"), "utf8"); } catch { return ""; } })();
const unclassified = all.filter((r) => !catalog.includes(`v${r.version}/${r.public_id}`) && !catalog.includes(`/${r.public_id}.`) && !catalog.includes(`\`${r.public_id}\``));

let md = `# BeeWise asset inventory (raw)

Generated by \`npm run assets:sync\` on ${new Date().toISOString().slice(0, 10)}. ${all.length} assets. Agents: read the classified catalog \`.agents/assets.md\` instead of this file.

## Unclassified (add to assets.md)

${unclassified.length ? unclassified.map((r) => `- ${deliveryUrl(r)}`).join("\n") : "None."}
`;

for (const [folder, items] of groups) {
  md += `\n## ${folder}\n\n| Name | Type | Size | Tags | Notes | URL |\n| --- | --- | --- | --- | --- | --- |\n`;
  for (const r of items) {
    const name = r.display_name || r.public_id.split("/").pop();
    const size = r.width ? `${r.width}×${r.height}` : `${Math.round((r.bytes || 0) / 1024)}KB`;
    const notes = r.context?.custom?.alt || r.context?.custom?.caption || "";
    md += `| ${cell(name)} | ${r.format || r.resource_type} | ${size} | ${cell((r.tags || []).join(", "))} | ${cell(notes)} | ${deliveryUrl(r)} |\n`;
  }
}

writeFileSync(resolve(root, ".agents/assets-inventory.md"), md);
console.log(`Wrote .agents/assets-inventory.md (${all.length} assets, ${unclassified.length} unclassified)`);
